/** 由图标清单生成 <svg class="sm-sprite"><defs><symbol>…</symbol></defs></svg>。 */
export function createSelectionMenuSprite(doc = document) {
    const NS = 'http://www.w3.org/2000/svg';
    const sprite = doc.createElementNS(NS, 'svg');
    sprite.setAttribute('class', 'sm-sprite');
    sprite.setAttribute('aria-hidden', 'true');
    const defs = doc.createElementNS(NS, 'defs');
    for (const icon of SELECTION_MENU_ICONS) {
        const symbol = doc.createElementNS(NS, 'symbol');
        symbol.setAttribute('id', icon.id);
        symbol.setAttribute('viewBox', icon.viewBox);
        const group = doc.createElementNS(NS, 'g');
        if (icon.transform) group.setAttribute('transform', icon.transform);
        for (const d of [icon.path, ...(icon.extraPaths || [])]) {
            const path = doc.createElementNS(NS, 'path');
            path.setAttribute('d', d);
            group.appendChild(path);
        }
        symbol.appendChild(group);
        defs.appendChild(symbol);
    }
    sprite.appendChild(defs);
    return sprite;
}

/** 生成一个 <svg class="sm-ic"><use href="#id"> 图标节点。 */
export function createSelectionMenuIcon(iconId, doc = document) {
    const NS = 'http://www.w3.org/2000/svg';
    const svg = doc.createElementNS(NS, 'svg');
    svg.setAttribute('class', 'sm-ic');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
    const use = doc.createElementNS(NS, 'use');
    // iOS 15 以下的 Safari 只认 xlink:href：两个都写，漏写会静默丢图标。
    use.setAttribute('href', `#${iconId}`);
    use.setAttributeNS('http://www.w3.org/1999/xlink', 'xlink:href', `#${iconId}`);
    svg.appendChild(use);
    return svg;
}

/** 全局只挂一份精灵（多次调用复用同一个节点）。 */
export function ensureSelectionMenuSprite(doc = document) {
    const existing = doc.querySelector('.sm-sprite');
    if (existing) return existing;
    const sprite = createSelectionMenuSprite(doc);
    (doc.body || doc.documentElement).appendChild(sprite);
    return sprite;
}
